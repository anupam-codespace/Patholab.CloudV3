import { NextRequest, NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { getCurrentUser, getDataFromToken } from '@/lib/auth';
import { revalidatePath } from 'next/cache';

export const dynamic = 'force-dynamic';

async function getAuthenticatedLabId(req: NextRequest): Promise<string | null> {
  const user = (await getDataFromToken(req)) || (await getCurrentUser());
  if (!user) return null;
  const userId = user.userId || (user as any).id;
  if (user.labId) return user.labId;

  if (userId) {
    const ownerLab = await prisma.lab.findFirst({
      where: { ownerId: userId },
      select: { id: true },
    });
    if (ownerLab) return ownerLab.id;

    const staffLab = await prisma.labStaff.findFirst({
      where: { userId, isActive: true },
      select: { labId: true },
    });
    if (staffLab) return staffLab.labId;

    if (user.role === "SUPER_ADMIN") {
      const firstLab = await prisma.lab.findFirst({
        where: { isActive: true },
        select: { id: true },
      });
      if (firstLab) return firstLab.id;
    }
  }

  return null;
}

// ============================================================================
// GET: List all report templates for authenticated workspace
// ============================================================================
export async function GET(req: NextRequest) {
  try {
    const labId = await getAuthenticatedLabId(req);
    if (!labId) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const templates = await prisma.reportTemplate.findMany({
      where: { labId },
      orderBy: { createdAt: 'desc' },
    });

    return NextResponse.json({
      success: true,
      templates,
      data: templates,
    });
  } catch (error: any) {
    console.error('GET /api/workspace/settings/templates Error:', error);
    return NextResponse.json(
      { error: error.message || 'Failed to fetch report templates' },
      { status: 500 }
    );
  }
}

// ============================================================================
// POST: Create template or perform gallery actions (ACTIVATE, DUPLICATE)
// ============================================================================
export async function POST(req: NextRequest) {
  try {
    const labId = await getAuthenticatedLabId(req);
    if (!labId) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const body = await req.json();
    const { action, id, name, type, config, headerText, footerText, showLogo, showSignature, showNabl } = body;

    // Action: Set Active Template
    if (action === 'ACTIVATE' && id) {
      await prisma.$transaction([
        prisma.reportTemplate.updateMany({
          where: { labId },
          data: { isActive: false },
        }),
        prisma.reportTemplate.update({
          where: { id, labId },
          data: { isActive: true },
        }),
      ]);

      revalidatePath('/workspace/settings/templates');
      revalidatePath('/workspace/reports/print');

      return NextResponse.json({
        success: true,
        message: 'Template activated successfully',
      });
    }

    // Action: Duplicate Template
    if (action === 'DUPLICATE' && id) {
      const source = await prisma.reportTemplate.findUnique({
        where: { id, labId },
      });

      if (!source) {
        return NextResponse.json({ error: 'Source template not found' }, { status: 404 });
      }

      const duplicate = await prisma.reportTemplate.create({
        data: {
          labId,
          name: `${source.name} (Copy)`,
          type: source.type,
          config: source.config as any,
          content: source.content as any,
          isActive: false,
        },
      });

      revalidatePath('/workspace/settings/templates');

      return NextResponse.json({
        success: true,
        message: 'Template duplicated successfully',
        template: duplicate,
      });
    }

    // Action: Standard Template Creation
    const count = await prisma.reportTemplate.count({ where: { labId } });
    const isFirst = count === 0;

    // Construct configuration object matching web builder
    const templateConfig = config || {
      header: {
        show: true,
        mode: 'standard',
        title: headerText || name || 'LAB REPORT',
      },
      footer: {
        show: true,
        mode: 'standard',
        text: footerText || 'Report Generated by System',
        signatures: showSignature ? [
          { title: 'Technician', show: true },
          { title: 'Consultant Pathologist', show: true },
        ] : [],
        showNabl: !!showNabl,
      },
      branding: {
        showLogo: showLogo !== false,
      },
    };

    const newTemplate = await prisma.reportTemplate.create({
      data: {
        labId,
        name: name || 'New Template',
        type: type === 'RADIOLOGY' ? 'LOCAL' : 'LOCAL',
        config: templateConfig,
        isActive: isFirst,
      },
    });

    revalidatePath('/workspace/settings/templates');

    return NextResponse.json({
      success: true,
      message: 'Template created successfully',
      template: newTemplate,
    });
  } catch (error: any) {
    console.error('POST /api/workspace/settings/templates Error:', error);
    return NextResponse.json(
      { error: error.message || 'Failed to create report template' },
      { status: 500 }
    );
  }
}
